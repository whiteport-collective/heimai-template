def status(heim: Heim, sources_arg: str | None, verbose: bool):
    print(f"Heim:     {heim.root.as_posix()} ({heim.rel(heim.plan)})")
    print(f"Agents:   {heim.rel(heim.agents_dir)}/   own source: agents/{heim.own}/")
    if not heim.agents_dir.is_dir():
        print("  no agents folder yet")
    else:
        for d in sorted(p for p in heim.agents_dir.iterdir() if p.is_dir()):
            if d.name == heim.own:
                n = len(files_under(d))
                print(f"  {heim.rel(d)}/  the Heim's own source, {n} files")
                continue
            s = read_source_file(d)
            if s is None:
                print(f"  {heim.rel(d)}/  no .source: not managed by heim-sync")
                continue
            if s.get("generated_by") != "heim-sync":
                print(f"  {heim.rel(d)}/  .source {s.get('source')!r}, not written by heim-sync (the next sync takes it over if it is a source)")
                continue
            objs = s.get("objects") or {}
            print(f"  {heim.rel(d)}/  {s.get('repo')} {s.get('commit')} ({s.get('version')}), synced {s.get('synced')}: "
                  + "; ".join(f"{len(v)} {k}" for k, v in objs.items()))
            edited = [r for r, hsh in (s.get("files") or {}).items()
                      if (d / r).exists() and digest((d / r).read_bytes()) != hsh]
            gone = [r for r in (s.get("files") or {}) if not (d / r).exists()]
            recorded = set(s.get("files") or {}) | {".source"}
            stray = [r for f in files_under(d) if (r := f.relative_to(d).as_posix()) not in recorded
                     and not r.startswith(CUSTOM + "/")]
            n_cust = len(files_under(d / CUSTOM))
            if n_cust:
                print(f"    customizations: {n_cust} files in {heim.rel(d / CUSTOM)}/ (the dry run says what each changes)")
            if stray:
                print(f"    ! added to the copy, removed by the next sync ({len(stray)}): {show(stray, 0 if verbose else LIST_LIMIT)}"
                      f"; a change goes in {heim.rel(d / CUSTOM)}/")
            if edited:
                print(f"    ! edited in the copy ({len(edited)}): {show(edited, 0 if verbose else LIST_LIMIT)}")
            if gone:
                print(f"    ! deleted from the copy ({len(gone)}): {show(gone, 0 if verbose else LIST_LIMIT)}")
            if s.get("missing"):
                print(f"    missing at the last sync: {len(s['missing'])} references")
    try:
        sources_dir = find_sources(sources_arg)
    except SystemExit as e:
        print(f"\nUpstream: not compared ({e})")
        return 0
    plan = make_plan(heim, sources_dir)
    print(f"\nUpstream: {sources_dir.as_posix()} ({plan.info.repo}@{plan.info.commit or '-'})")
    print_customizations(plan)
    if nothing_to_do(plan):
        print("Up to date: a sync would change nothing.")
    else:
        print("A sync would change:")
        for fp in plan.folders:
            if fp.new or fp.update or fp.delete:
                print(f"  {heim.rel(fp.dest)}/: {len(fp.new)} new, {len(fp.update)} changed, {len(fp.delete)} removed")
        if plan.pointers_write or plan.pointers_remove:
            print(f"  pointers: {len(plan.pointers_write)} to write, {len(plan.pointers_remove)} to remove")
        if plan.settings_change:
            print("  hooks in .claude/settings.json")
        print("Run dry-run for the details.")
    if plan.cl.errors:
        print(f"{len(plan.cl.errors)} references do not resolve; dry-run lists them.")
    return 0


# ---------- main ----------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="heim-sync", description=__doc__.split("\n")[0],
                                 epilog="Policy: the Heim's governance framework (see tool.md). A dry run never writes.")
    ap.add_argument("command", nargs="?", default="dry-run", choices=["dry-run", "run", "status"])
    ap.add_argument("--heim", help="the Heim (default: the nearest above the current folder)")
    ap.add_argument("--from", dest="sources", help="the sources folder: the agents/ of a HeimAI clone")
    ap.add_argument("--yes", action="store_true", help="run: the person has said yes to writing into this Heim")
    ap.add_argument("--allow-missing", action="store_true", help="run: copy what resolves even when references do not")
    ap.add_argument("--allow-unreleased", action="store_true", help="run: sync from a branch or uncommitted sources")
    ap.add_argument("--discard-edits", action="store_true", help="run: overwrite files that were edited in the copy")
    ap.add_argument("--verbose", "-v", action="store_true", help="list every file")
    args = ap.parse_args(argv)

    heim = load_heim(args.heim)
    if args.command == "status":
        print("heim-sync status\n")
        return status(heim, args.sources, args.verbose)

    sources_dir = find_sources(args.sources)
    plan = make_plan(heim, sources_dir)
    if args.command == "dry-run" or not args.yes:
        print("heim-sync dry-run (nothing is written)\n")
        print_plan(plan, args.verbose)
        blockers = plan.blockers(args)
        print()
        if nothing_to_do(plan):
            print("Nothing to do: the Heim is up to date.")
        if blockers:
            print("A run would stop here:")
            for b in blockers:
                print(f"  - {b}")
        if args.command == "run":
            print("Nothing written: run needs --yes, given only after the person has seen this and said yes.")
            return 1
        return 0

    blockers = plan.blockers(args)
    if blockers:
        print("heim-sync run: stopped, nothing written\n")
        print_plan(plan, args.verbose)
        print("\nStopped because:")
        for b in blockers:
            print(f"  - {b}")
        return 1
    if nothing_to_do(plan):
        print("heim-sync run: nothing to do, the Heim is up to date.")
        for c, msg in plan.upstream_changed:
            print(f"  ! {c} {msg}")
        return 0
    apply(plan)
    print("heim-sync run: receipt\n")
    print_plan(plan, args.verbose, done=True)
    print("\nDone. Commit the changes in the Heim; new pointers show up in the next session.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

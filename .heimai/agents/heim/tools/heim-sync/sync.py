def first_sentence(text: str) -> str:
    text = " ".join(str(text or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text).rstrip(".")


def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)



def prune(dest: Path):
    """Remove folders inside a managed folder that hold nothing but caches (__pycache__, .DS_Store)."""
    if not dest.is_dir():
        return
    keep = dest / CUSTOM     # the Heim's customizations, caches included, are never touched (story 5.10)
    for d in sorted((p for p in dest.rglob("*") if p.is_dir() and p != keep and keep not in p.parents),
                    key=lambda p: len(p.parts), reverse=True):
        if d.exists() and not any(f.is_file() and not skipped_file(f.relative_to(dest)) for f in d.rglob("*")):
            shutil.rmtree(d)


def apply(plan: Plan):
    h = plan.heim
    for fp in plan.folders:
        if fp.blocked:
            continue
        dest = fp.dest
        if fp.remove_folder:
            for rel in fp.delete:
                (dest / rel).unlink()
            (dest / ".source").unlink(missing_ok=True)
        else:
            for rel in fp.new + fp.update:
                (dest / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(fp.files[rel], dest / rel)
            for rel in fp.delete:
                (dest / rel).unlink()
        prune(dest)
        if fp.remove_folder:
            if dest.exists() and not any(dest.iterdir()):
                dest.rmdir()
        elif fp.write_source:
            dest.mkdir(parents=True, exist_ok=True)
            (dest / ".source").write_text(fp.source_text, encoding="utf-8", newline="\n")
    for p, (content, _) in plan.pointers_write.items():
        f = h.root / p
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding="utf-8", newline="\n")
    for p in plan.pointers_remove:
        f = h.root / p
        f.unlink()
        if f.name == "SKILL.md" and f.parent.exists() and not any(f.parent.iterdir()):
            f.parent.rmdir()
    if plan.settings_change and plan.settings_new is not None:
        f = h.root / ".claude" / "settings.json"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps(plan.settings_new, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    if plan.agents_md_new is not None:
        (h.root / "AGENTS.md").write_text(plan.agents_md_new, encoding="utf-8", newline="\n")


def nothing_to_do(plan: Plan) -> bool:
    return not (any(fp.new or fp.update or fp.delete or fp.write_source or fp.remove_folder
                    for fp in plan.folders if not fp.blocked)
                or plan.pointers_write or plan.pointers_remove or plan.settings_change or plan.agents_md_new is not None)



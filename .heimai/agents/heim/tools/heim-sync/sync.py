@dataclass
class SourceInfo:
    folder: Path
    repo: str
    path: str
    commit: str
    branch: str
    default_branch: str
    dirty: bool
    tags: list[str]

    def ready(self) -> str:
        """Why the source is not reviewed content, or "" (the WDS rule: default branch, nothing uncommitted)."""
        if not self.commit:
            return ""
        why = []
        if self.default_branch and self.branch != self.default_branch:
            why.append(f"on branch '{self.branch}', not '{self.default_branch}'")
        if self.dirty:
            why.append("uncommitted changes under the sources folder")
        return "; ".join(why)


def find_sources(arg: str | None) -> Path:
    if arg:
        p = Path(arg).expanduser().resolve()
        if not p.is_dir():
            sys.exit(f"--from {arg}: no such folder")
        return p
    default = dev_root() / "Heim" / "HeimAI" / "agents"
    if (default / "heim").is_dir():
        return default.resolve()
    sys.exit(f"No sources: {default} has no released agents yet. Give --from <the agents/ folder of HeimAI, "
             f"cloned anywhere>.")


def source_info(folder: Path) -> SourceInfo:
    code, top = git(["rev-parse", "--show-toplevel"], folder)
    if code != 0:
        return SourceInfo(folder, folder.name, folder.as_posix(), "", "", "", False, [])
    top_p = Path(top).resolve()
    _, url = git(["remote", "get-url", "origin"], folder)
    repo = re.sub(r"\.git$", "", url.rstrip("/").split("/")[-1].split(":")[-1]) if url else top_p.name
    _, commit = git(["rev-parse", "--short", "HEAD"], folder)
    _, branch = git(["branch", "--show-current"], folder)
    c, ref = git(["symbolic-ref", "--short", "refs/remotes/origin/HEAD"], folder)
    default_branch = ref.split("/", 1)[1] if c == 0 and "/" in ref else ("main" if branch in ("main", "master") else "main")
    _, dirty = git(["status", "--porcelain", "--", "."], folder)
    _, tags = git(["tag", "--points-at", "HEAD"], folder)
    return SourceInfo(folder, repo, folder.relative_to(top_p).as_posix(), commit, branch, default_branch,
                      bool(dirty), tags.split() if tags else [])


# ---------- the closure ----------

@dataclass(frozen=True)
class Obj:
    source: str
    kind: str
    name: str      # the object's name; for templates and guardrails its path under the kind folder
    rel: str       # path under the source folder: a folder or a file

    @property
    def label(self) -> str:
        return f"{self.source}/{self.kind}/{self.name}"


class Closure:
    def __init__(self, heim: Heim, sources_dir: Path):
        self.heim = heim
        self.sources_dir = sources_dir
        self.sources = sorted(d.name for d in sources_dir.iterdir()
                              if d.is_dir() and not d.name.startswith((".", "_")))
        self.own_dir = heim.agents_dir / heim.own
        self.cust_dir = heim.agents_dir / "heim" / CUSTOM
        self.objects: dict[Obj, set[str]] = {}       # object -> referrers
        self.own_only: set[Obj] = set()               # resolved only in the Heim's own source
        self.errors: list[str] = []
        self.notes: list[str] = list(heim.notes)
        self.agents: list[Obj] = []                   # woken agents, in order
        self.skills: list[Obj] = []                   # skills that get pointers, in order
        self.extra_files: dict[str, set[str]] = {}    # source -> files outside an object's folder (shared references)
        if heim.own in self.sources:
            self.errors.append(f"own_source '{heim.own}' has the same name as a source in {sources_dir}; "
                               "set another own_source in the floor plan")

    # -- locating --

    def src_dir(self, source: str) -> Path:
        return self.own_dir if source == self.heim.own else self.sources_dir / source

    def locate(self, source: str, kind: str, ref: str) -> Obj | None:
        base = self.src_dir(source)
        ref = ref.strip("/")
        if ref.startswith(kind + "/"):
            ref = ref[len(kind) + 1:]
        if kind in ("agents", "skills", "tools", "apps"):
            name = ref.split("/")[0]
            if name.endswith(".md") and kind == "skills" and (base / "skills" / name).is_file():
                return Obj(source, kind, name[:-3], f"skills/{name}")
            folder = base / kind / name
            if kind in MAIN_FILE and kind != "tools" and kind != "apps" and not (folder / MAIN_FILE[kind]).is_file():
                return None
            return Obj(source, kind, name, f"{kind}/{name}") if folder.is_dir() else None
        exts = ("", ".md", ".yaml", ".yml", ".html", ".json") if kind == "templates" else ("", ".md")
        for ext in exts:
            p = base / kind / (ref + ext)
            if p.exists():
                rel = f"{kind}/{ref}{ext}"
                name = rel[len(kind) + 1:]
                if p.is_file():
                    name = re.sub(r"\.(md|ya?ml|json)$", "", name)
                return Obj(source, kind, name, rel)
        return None

    def resolve(self, kind: str, ref: str, ctx: str) -> tuple[Obj | None, str]:
        """(object, problem). A prefix names the source (`taste/design-taste-frontend`); without one the
        reference means the referrer's own source when that is a synced source other than heim, then heim,
        then the Heim's own source (an object only the Heim has)."""
        parts = ref.split("/", 1)
        if len(parts) == 2 and (parts[0] in self.sources or parts[0] == self.heim.own):
            order = [parts[0]]
            ref = parts[1]
        else:
            order = ([ctx] if ctx not in ("heim", self.heim.own) else []) + ["heim", self.heim.own]
        for src in order:
            if src != self.heim.own and src not in self.sources:
                continue
            o = self.locate(src, kind, ref)
            if o:
                return o, ""
        where = " or ".join(dict.fromkeys(s for s in order if s in self.sources or s == self.heim.own))
        return None, f"not found in {where or 'any source'}"

    def is_file_obj(self, o: Obj) -> bool:
        return (self.src_dir(o.source) / o.rel).is_file()

    def cust(self, o: Obj) -> tuple[Path | None, Path | None]:
        """(the customization replacing the object's main file, the customization adding to it), None where absent.
        A folder object: <rel>/<main file> and <rel>/additions.md; a file object: <rel> and <stem>.additions<suffix>."""
        if o.source == self.heim.own:
            return None, None
        if self.is_file_obj(o):
            p = Path(o.rel)
            rep, add = self.cust_dir / o.rel, self.cust_dir / p.parent / f"{p.stem}.additions{p.suffix}"
        else:
            rep = self.cust_dir / o.rel / MAIN_FILE[o.kind] if o.kind in MAIN_FILE else None
            add = self.cust_dir / o.rel / ADDITIONS
        return (rep if rep and rep.is_file() else None), (add if add.is_file() else None)

    # -- walking --

    def add(self, o: Obj, referrer: str) -> bool:
        new = o not in self.objects
        self.objects.setdefault(o, set()).add(referrer)
        if o.source == self.heim.own:
            self.own_only.add(o)
        return new

    def walk(self):
        queue: list[Obj] = []
        for ref in self.heim.woken:
            o, why = self.find_woken("agents", ref)
            if not o:
                self.errors.append(f"heim.yaml agents: {ref}: {why}")
                continue
            self.agents.append(o)
            if self.add(o, "heim.yaml agents"):
                queue.append(o)
        for ref in self.heim.capabilities:
            o, why = self.find_woken("skills", ref)
            if not o:
                self.errors.append(f"heim.yaml capabilities: {ref}: {why}")
                continue
            if o not in self.skills:
                self.skills.append(o)
            if self.add(o, "heim.yaml capabilities"):
                queue.append(o)
        while queue:
            o = queue.pop(0)
            for child in self.children(o):
                if o.kind == "agents" and child.kind == "skills" and child not in self.skills:
                    self.skills.append(child)
                if self.add(child, o.label):
                    queue.append(child)
        self.add_dependencies()

    def find_woken(self, kind: str, ref: str) -> tuple[Obj | None, str]:
        if "/" in ref:
            return self.resolve(kind, ref, "heim")
        hits = [o for s in ["heim"] + [s for s in self.sources if s != "heim"] if (o := self.locate(s, kind, ref))]
        if not hits:
            o = self.locate(self.heim.own, kind, ref) if self.own_dir.is_dir() else None
            return (o, "") if o else (None, f"not found in {', '.join(self.sources)}"
                                      + (f" or {self.heim.own}" if self.own_dir.is_dir() else ""))
        if len(hits) > 1 and hits[0].source != "heim":
            return None, f"in several sources ({', '.join(h.source for h in hits)}); write it with its source, e.g. {hits[0].source}/{ref}"
        return hits[0], ""

    def children(self, o: Obj) -> list[Obj]:
        if o.kind not in FOLLOW:
            return []
        main = MAIN_FILE[o.kind]
        fm_files = []
        base = self.src_dir(o.source) / o.rel
        main_path = base if base.is_file() else base / main
        if main_path.is_file():
            fm_files.append(main_path)
        fm_files += [p for p in self.cust(o) if p]      # a customization may name tools, guardrails … of its own
        out: list[Obj] = []
        for f in fm_files:
            fm, problem = front_matter(f)
            if problem:
                self.notes.append(f"{o.label}: {problem}")
            for key in FOLLOW[o.kind]:
                for ref in as_list(fm.get(key)):
                    if key == "references":
                        self.reference(o, ref)
                        continue
                    child, why = self.resolve(key, ref, o.source)
                    if child:
                        out.append(child)
                    elif key == "apps" and o.kind == "skills":
                        # a skill's apps: are programs it needs (layer 7), unless a Heim app has the name
                        continue
                    else:
                        self.errors.append(f"{o.label} -> {key[:-1]} {ref}: {why}")
        if o.kind == "tools" and base.is_dir():
            out += self.sibling_tools(o, base, {c.name for c in out})
        return out

    def sibling_tools(self, o: Obj, base: Path, declared: set[str]) -> list[Obj]:
        """Tools a tool's scripts load from beside it (`parent / "heim-floor"`, `../heim-floor/`) without declaring them
        in `tools:`. Taken anyway, so the copy runs, and noted so the tool's front matter can say it."""
        found = []
        for f in files_under(base):
            if f.suffix not in (".py", ".mjs", ".js", ".cjs", ".ps1", ".sh"):
                continue
            text = f.read_text(encoding="utf-8", errors="replace")
            for name in set(re.findall(r'parent\s*/\s*["\']([a-z0-9][a-z0-9-]*)["\']', text)) | \
                    set(re.findall(r'\.\./([a-z0-9][a-z0-9-]*)/', text)):
                if name == o.name or name in declared or name in (x.name for x in found):
                    continue
                sib = self.locate(o.source, "tools", name)
                if sib:
                    found.append(sib)
                    self.notes.append(f"{o.label} loads tools/{name} from beside it without `tools: [{name}]` in tool.md; taken anyway")
        return found

    def reference(self, o: Obj, ref: str):
        """A skill's references: its own references/ folder, or another skill's (`bugreport-anything/business-impact`)."""
        base = self.src_dir(o.source) / o.rel
        if base.is_file():
            return
        tries = [f"{o.rel}/references/{ref}", f"{o.rel}/references/{ref}.md", f"{o.rel}/{ref}", f"{o.rel}/{ref}.md"]
        if "/" in ref:
            first, rest = ref.split("/", 1)
            tries += [f"skills/{first}/references/{rest}", f"skills/{first}/references/{rest}.md"]
        for t in tries:
            p = self.src_dir(o.source) / t
            if p.exists():
                if not t.startswith(o.rel + "/") and o.source != self.heim.own:
                    self.extra_files.setdefault(o.source, set()).update(
                        f.relative_to(self.src_dir(o.source)).as_posix() for f in files_under(p))
                return
        self.errors.append(f"{o.label} -> reference {ref}: not found beside the skill")

    def add_dependencies(self):
        """dependencies/*.md whose `for:` names a copied object; one without `for:` serves its whole source."""
        names: dict[str, set[str]] = {}
        for o in self.objects:
            names.setdefault(o.source, set()).add(o.name.split("/")[-1].rsplit(".", 1)[0])
        for src in [s for s in self.sources if s in names] + ([self.heim.own] if self.own_dir.is_dir() else []):
            for f in sorted((self.src_dir(src) / "dependencies").glob("*.md")):
                fm, _ = front_matter(f)
                wanted = as_list(fm.get("for"))
                hit = False
                if not wanted:
                    hit = src in names
                    if hit:
                        self.notes.append(f"{src}/dependencies/{f.name} has no `for:`; taken because something from {src} is")
                for w in wanted:
                    s, _, n = w.rpartition("/")
                    if n in names.get(s or src, set()):
                        hit = True
                if hit:
                    self.add(Obj(src, "dependencies", f.stem, f"dependencies/{f.name}"), "dependencies")

    # -- results --

    def selected(self) -> dict[str, dict[str, Path]]:
        """source -> {path under the source: file in the sources folder}, for every synced source."""
        out: dict[str, dict[str, Path]] = {}
        for o in self.objects:
            if o.source == self.heim.own:
                continue
            base = self.sources_dir / o.source
            for f in files_under(base / o.rel):
                out.setdefault(o.source, {})[f.relative_to(base).as_posix()] = f
        for src, rels in self.extra_files.items():
            for r in rels:
                out.setdefault(src, {})[r] = self.sources_dir / src / r
        for src in out:
            for name in SOURCE_ROOT_FILES:
                p = self.sources_dir / src / name
                if p.is_file():
                    out[src][name] = p
        return out

    def target(self, o: Obj) -> tuple[str, str | None, bool]:
        """(path the pointer reads, the customization adding to it or None, whether a customization replaces it),
        relative to the Heim root."""
        rel = o.rel if o.rel.endswith(".md") else f"{o.rel}/{MAIN_FILE[o.kind]}"
        if o.source == self.heim.own:
            return self.heim.rel(self.own_dir / rel), None, False
        rep, add = self.cust(o)
        path = self.heim.rel(rep) if rep else self.heim.rel(self.heim.agents_dir / o.source / rel)
        return path, (self.heim.rel(add) if add else None), bool(rep)

    def other_replacements(self, o: Obj) -> str | None:
        """The customization folder of a folder object when it holds files besides the main file and additions.md."""
        folder = self.cust_dir / o.rel
        if o.source == self.heim.own or not folder.is_dir():
            return None
        rest = [f for f in files_under(folder) if f.relative_to(folder).as_posix() not in (MAIN_FILE.get(o.kind), ADDITIONS)]
        return self.heim.rel(folder) if rest else None


# ---------- .source ----------

def read_source_file(folder: Path) -> dict | None:
    f = folder / ".source"
    if not f.is_file():
        return None
    text = f.read_text(encoding="utf-8", errors="replace")
    try:
        data = yaml.safe_load(text)
        if isinstance(data, dict):
            return data
    except yaml.YAMLError:
        pass
    m = re.search(r"^source:\s*(.+)$", text, re.M)
    return {"source": m.group(1).strip() if m else ""}


def source_text(name: str, info: SourceInfo, objects: dict[str, list[str]], files: dict[str, str],
                missing: list[str], own: str) -> str:
    commit = info.commit + ("+uncommitted" if info.dirty else "") if info.commit else "not a git repo"
    version = ", ".join(info.tags) if info.tags else "unreleased"
    data = {
        "generated_by": "heim-sync",
        "source": f"{info.repo}@{info.commit or '-'} {info.path}/{name}",
        "name": name,
        "repo": info.repo,
        "path": f"{info.path}/{name}",
        "commit": commit,
        "branch": info.branch or None,
        "version": version,
        "synced": date.today().isoformat(),
        "objects": objects,
        "missing": missing or None,
        "files": files,
    }
    data = {k: v for k, v in data.items() if v is not None}
    head = (f"# Written by heim-sync. This folder is a copy of the source named below: never edit it.\n"
            f"# The Heim's changes to it go in agents/heim/{CUSTOM}/ (never touched by the sync): the same path replaces, "
            f"{ADDITIONS} adds.\n# What only this Heim has goes in agents/{own}/; changes for every Heim go upstream as a pull request.\n")
    return head + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200)


def without_date(text: str) -> str:
    return re.sub(r"^synced:.*$", "", text, flags=re.M)



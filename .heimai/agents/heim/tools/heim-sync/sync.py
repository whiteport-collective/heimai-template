# ---------- hooks ----------

def hooks_of(path: Path) -> tuple[dict, str]:
    """The hooks a dependencies file declares: front matter `hooks:`, or a fenced yaml block with top-level `hooks:`."""
    fm, _ = front_matter(path)
    if isinstance(fm.get("hooks"), dict):
        return fm["hooks"], ""
    text = path.read_text(encoding="utf-8", errors="replace")
    for block in re.findall(r"```ya?ml\s*\n(.*?)```", text, re.S):
        try:
            data = yaml.safe_load(block)
        except yaml.YAMLError as e:
            return {}, f"its yaml block does not parse: {e}"
        if isinstance(data, dict) and isinstance(data.get("hooks"), dict):
            return data["hooks"], ""
    return {}, ""


def merge_hooks(settings: dict, wanted: dict[str, dict]) -> dict:
    """settings with every heim-sync hook replaced by `wanted` ({label: hooks}); other hooks stay as they are."""
    out = json.loads(json.dumps(settings))
    hooks = out.get("hooks") if isinstance(out.get("hooks"), dict) else {}
    for event in list(hooks):
        groups = []
        for g in hooks[event] if isinstance(hooks[event], list) else []:
            if isinstance(g, dict) and isinstance(g.get("hooks"), list):
                g = dict(g, hooks=[h for h in g["hooks"] if HOOK_MARK not in str(h.get("command", ""))])
                if not g["hooks"]:
                    continue
            groups.append(g)
        if groups:
            hooks[event] = groups
        else:
            del hooks[event]
    for label, decl in sorted(wanted.items()):
        for event, groups in decl.items():
            for g in groups if isinstance(groups, list) else []:
                g = json.loads(json.dumps(g))
                for h in g.get("hooks", []):
                    if h.get("type") == "command" and "command" in h:
                        h["command"] = f"{h['command'].rstrip()}  {HOOK_MARK} {label}"
                hooks.setdefault(event, []).append(g)
    if hooks:
        out["hooks"] = hooks
    else:
        out.pop("hooks", None)
    return out



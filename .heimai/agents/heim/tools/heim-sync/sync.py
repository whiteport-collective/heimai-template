def session_block(cl: Closure, extra: str = "") -> str | None:
    """The session lines for AGENTS.md, when a woken agent uses the handover skill; None otherwise."""
    skill = next((o for o in cl.skills if o.name == "handover"), None)
    if not skill:
        return None
    tpl = cl.src_dir(skill.source) / SESSION_TEMPLATE
    if not tpl.is_file():
        return None
    h = cl.heim
    body = tpl.read_text(encoding="utf-8").strip("\n")
    body = (body.replace("{{agents}}", f"{h.rel(h.agents_dir)}/{skill.source}")
                .replace("{{sessions}}", h.sessions)
                .replace("{{users}}", h.users)
                .replace("{{plan}}", h.rel(h.plan)))
    src = f"{h.rel(h.agents_dir)}/{skill.source}/{SESSION_TEMPLATE.as_posix()}"
    if extra:
        body += "\n\n" + extra
    return f"<!-- heim:session  {MARK} From {src}. -->\n{body}\n{SESSION_END}"


def with_session_block(text: str, block: str) -> str | None:
    """AGENTS.md with the block between the markers (or in place of a lone start marker); None when it has no marker."""
    m = SESSION_START.search(text)
    if not m:
        return None
    end = text.find(SESSION_END, m.end())
    stop = end + len(SESSION_END) if end >= 0 else m.end()
    return text[:m.start()] + block + text[stop:]



@dataclass
class FolderPlan:
    name: str
    dest: Path
    files: dict[str, Path]
    new: list[str] = field(default_factory=list)
    update: list[str] = field(default_factory=list)
    delete: list[str] = field(default_factory=list)
    edited: list[str] = field(default_factory=list)
    blocked: str = ""
    old: dict | None = None
    source_text: str = ""
    write_source: bool = False
    remove_folder: bool = False


@dataclass
class Plan:
    heim: Heim
    cl: Closure
    info: SourceInfo
    folders: list[FolderPlan] = field(default_factory=list)
    left_alone: list[str] = field(default_factory=list)
    overrides: list[tuple[str, str]] = field(default_factory=list)          # (customization, synced path it replaces)
    upstream_changed: list[tuple[str, str]] = field(default_factory=list)   # (customization, diff stat)
    customized: list[tuple[Obj, list[str]]] = field(default_factory=list)   # (object, how: adds, replaces …)
    cust_errors: list[str] = field(default_factory=list)                    # stop a run
    cust_notes: list[str] = field(default_factory=list)
    pointers_write: dict[str, tuple[str, str]] = field(default_factory=dict)   # path -> (content, add|replace)
    pointers_remove: list[str] = field(default_factory=list)
    pointers_conflict: list[str] = field(default_factory=list)
    pointers_kept: list[str] = field(default_factory=list)
    pointers_unresolved: list[str] = field(default_factory=list)
    hooks: dict[str, dict] = field(default_factory=dict)
    hook_problems: list[str] = field(default_factory=list)
    settings_new: dict | None = None
    settings_change: bool = False
    agents_md_new: str | None = None       # AGENTS.md with the session lines, when they change
    agents_md_note: str = ""

    def blockers(self, args) -> list[str]:
        out = []
        if self.cl.errors and not args.allow_missing:
            out.append(f"{len(self.cl.errors)} references do not resolve (fix them, or --allow-missing copies what does)")
        why = self.info.ready()
        if why and not args.allow_unreleased:
            out.append(f"the source is not reviewed content: {why} (--allow-unreleased to sync it anyway)")
        for fp in self.folders:
            if fp.blocked:
                out.append(f"{self.heim.rel(fp.dest)}/: {fp.blocked}")
            if fp.edited and not args.discard_edits:
                out.append(f"{self.heim.rel(fp.dest)}/: {len(fp.edited)} files were edited in the copy "
                           f"({show(fp.edited, LIST_LIMIT)}); move each change to {self.heim.rel(self.cl.cust_dir)}/ at the "
                           f"same path, as {ADDITIONS} when it adds (or upstream), or --discard-edits")
        out += self.cust_errors
        out += self.hook_problems
        return out


def is_additions(name: str) -> bool:
    return name == ADDITIONS or ".additions." in name


def app_customization(plan: Plan, o: Obj, fp: FolderPlan, claimed: set[str]):
    """An app's customization folder, checked against the points its app.md declares (story 5.11). A file at a synced
    path is a fork of that file: allowed, and said at every run, since it no longer updates."""
    cl, heim = plan.cl, plan.heim
    folder = cl.cust_dir / o.rel
    if not folder.is_dir():
        return
    fm, _ = front_matter(cl.src_dir(o.source) / o.rel / MAIN_FILE["apps"])
    declared = [p for p in as_list(fm.get("customizable")) if p in APP_POINTS]
    forkable = [x.rstrip("/") + "/" for x in as_list(fm.get("forkable"))]   # where the app reads a fork in place of its own
    used: list[str] = []
    forks: list[str] = []
    for f in files_under(folder):
        rel = f.relative_to(cl.cust_dir).as_posix()
        inner = rel[len(o.rel) + 1:]
        claimed.add(rel)
        if rel in fp.files and not any(inner.startswith(x) for x in forkable):
            plan.cust_errors.append(f"{heim.rel(f)} has the path of a synced file, but apps/{o.name} never reads a copy of "
                                    f"it (forkable: {', '.join(forkable) or 'nothing'}); use a point it declares "
                                    f"({', '.join(declared) or 'none yet'}), or propose the change upstream")
            continue
        if rel in fp.files:
            forks.append(inner)
            plan.overrides.append((heim.rel(f), f"{o.source}/{rel}"))
            plan.cust_notes.append(f"{heim.rel(f)} is a fork of {o.source}/{rel}: it no longer updates; a point the app "
                                   f"declares ({', '.join(declared) or 'none yet'}) keeps a customization updating")
            recorded = ((fp.old or {}).get("files") or {}).get(rel)
            new = fp.files[rel].read_bytes()
            if recorded and recorded != digest(new):
                old_copy = fp.dest / rel
                stat = diffstat(old_copy.read_bytes(), new) if old_copy.exists() else "changed"
                plan.upstream_changed.append((heim.rel(f), f"forks {o.source}/{rel}, which changed upstream since the last "
                                                           f"sync ({stat}); compare and take in what you want"))
            continue
        point = next((p for p in declared if any(inner == x or (x.endswith("/") and inner.startswith(x)) for x in APP_POINTS[p])), None)
        if point:
            used.append(point if point != "plugins" else f"plugin {inner.split('/')[1]}" if inner.count("/") >= 2 else point)
        else:
            plan.cust_errors.append(f"{heim.rel(f)} is not one of the points apps/{o.name} declares "
                                    f"(customizable: {', '.join(declared) or 'none'}; see its app.md)")
    how = list(dict.fromkeys(used)) + [f"forks {x}" for x in forks]
    if how:
        plan.customized.append((o, how))


def customizations(plan: Plan):
    """What each customization changes, upstream changes under a replacement, and what changes nothing (story 5.10).
    The folder is the list: nothing is declared anywhere else, so nothing can disagree with it."""
    cl, heim = plan.cl, plan.heim
    folders = {fp.name: fp for fp in plan.folders if not fp.remove_folder}
    synced_paths = {r for fp in folders.values() for r in fp.files}
    # an own-source file at a synced path changes nothing (the synced object is found first): say where it goes now
    for f in files_under(cl.own_dir):
        rel = f.relative_to(cl.own_dir).as_posix()
        if rel in synced_paths:
            plan.cust_errors.append(f"{heim.rel(f)} has the path of a synced file and changes nothing; a change to a "
                                    f"synced capability goes in {heim.rel(cl.cust_dir)}/{rel}")
    if not cl.cust_dir.is_dir():
        return
    claimed: set[str] = set()
    for o in sorted(cl.objects, key=lambda o: (KINDS.index(o.kind), o.name)):
        if o.source == heim.own or o.source not in folders:
            continue
        fp = folders[o.source]
        if o.kind == "apps":
            app_customization(plan, o, fp, claimed)
            continue
        if cl.is_file_obj(o):
            files = [p for p in cl.cust(o) if p]
        else:
            files = files_under(cl.cust_dir / o.rel)
        how: list[str] = []
        for f in files:
            rel = f.relative_to(cl.cust_dir).as_posix()
            claimed.add(rel)
            inner = rel[len(o.rel) + 1:] if rel.startswith(o.rel + "/") else Path(rel).name
            if is_additions(f.name):
                how.append("adds")
            elif rel in fp.files:
                if o.kind == "guardrails":
                    plan.cust_errors.append(f"{heim.rel(f)} replaces a guardrail; a guardrail can only be tightened here: "
                                            f"write {Path(rel).stem}.additions{Path(rel).suffix} beside it instead")
                how.append(f"replaces {inner}")
                plan.overrides.append((heim.rel(f), f"{o.source}/{rel}"))
                recorded = ((fp.old or {}).get("files") or {}).get(rel)
                new = fp.files[rel].read_bytes()
                if recorded and recorded != digest(new):
                    old_copy = fp.dest / rel
                    stat = diffstat(old_copy.read_bytes(), new) if old_copy.exists() else "changed"
                    plan.upstream_changed.append((heim.rel(f), f"replaces {o.source}/{rel}, which changed upstream since "
                                                               f"the last sync ({stat}); compare and take in what you want"))
            else:
                how.append(f"adds {inner}")
        if how:
            plan.customized.append((o, list(dict.fromkeys(how))))
    for f in files_under(cl.cust_dir):
        rel = f.relative_to(cl.cust_dir).as_posix()
        if rel in claimed:
            continue
        parts = rel.split("/")
        plain = re.sub(r"\.additions(\.[^./]+)$", r"\1", rel)
        known = any((cl.sources_dir / s / plain).exists() or (len(parts) > 1 and (cl.sources_dir / s / parts[0] / parts[1]).is_dir())
                    for s in cl.sources)
        if known:
            plan.cust_notes.append(f"{heim.rel(f)} changes something not woken in this Heim; it is not used")
        else:
            plan.cust_errors.append(f"{heim.rel(f)} matches nothing in the sources: a typo, or a capability only this "
                                    f"Heim has, which goes in {heim.rel(cl.own_dir)}/")


def make_plan(heim: Heim, sources_dir: Path) -> Plan:
    info = source_info(sources_dir)
    cl = Closure(heim, sources_dir)
    cl.walk()
    plan = Plan(heim, cl, info)
    selected = cl.selected()

    # one folder per synced source
    for src in sorted(selected):
        dest = heim.agents_dir / src
        fp = FolderPlan(src, dest, selected[src])
        fp.old = read_source_file(dest) if dest.exists() else None
        existing = {f.relative_to(dest).as_posix(): f for f in files_under(dest)} if dest.exists() else {}
        existing.pop(".source", None)
        existing = {r: f for r, f in existing.items() if not r.startswith(CUSTOM + "/")}   # never the Heim's customizations
        if dest.exists() and fp.old is None and existing:
            fp.blocked = "has no .source: a source or a hand-made folder; heim-sync never writes into it"
        elif fp.old is not None and "generated_by" not in fp.old:
            last = str(fp.old.get("source", "")).split()[-1:] or [""]
            if not last[0].rstrip("/").endswith("/" + src):
                fp.blocked = f".source names {fp.old.get('source')!r}, not the source {src}"
        recorded = (fp.old or {}).get("files") or {}
        for rel, f in sorted(fp.files.items()):
            body = f.read_bytes()
            if rel not in existing:
                fp.new.append(rel)
            elif not same(existing[rel].read_bytes(), body):
                fp.update.append(rel)
        fp.delete = sorted(r for r in existing if r not in fp.files)
        for rel in fp.update + fp.delete:
            if rel in recorded and recorded[rel] != digest(existing[rel].read_bytes()):
                fp.edited.append(rel)
            elif rel in fp.delete and recorded and rel not in recorded:
                fp.edited.append(rel)      # added to the copy by hand: the sync would delete it (story 5.10, risk 1)
        objects: dict[str, list[str]] = {}
        for o in sorted(cl.objects, key=lambda o: (KINDS.index(o.kind), o.name)):
            if o.source == src:
                objects.setdefault(o.kind, []).append(o.name)
        missing = sorted(e.split(": not found")[0] for e in cl.errors)
        fp.source_text = source_text(src, info, objects, {r: digest(f.read_bytes()) for r, f in sorted(fp.files.items())},
                                     missing if src == "heim" else [], heim.own)
        old_text = (dest / ".source").read_text(encoding="utf-8") if (dest / ".source").exists() else ""
        fp.write_source = without_date(old_text) != without_date(fp.source_text)
        plan.folders.append(fp)

    # managed folders nothing is selected from any more, and folders heim-sync does not manage
    if heim.agents_dir.is_dir():
        for d in sorted(p for p in heim.agents_dir.iterdir() if p.is_dir()):
            if d.name in selected or d.name == heim.own:
                continue
            old = read_source_file(d)
            if old and old.get("generated_by") == "heim-sync":
                fp = FolderPlan(d.name, d, {}, old=old, remove_folder=True)
                fp.delete = [r for f in files_under(d) if not (r := f.relative_to(d).as_posix()).startswith(CUSTOM + "/")]
                plan.folders.append(fp)
            else:
                plan.left_alone.append(f"{heim.rel(d)}/ ({'no .source' if old is None else '.source not written by heim-sync'})")

    customizations(plan)

    # pointers
    wanted: dict[str, str] = {}
    names_seen: dict[str, str] = {}
    for o in cl.agents:
        for p, c in agent_pointers(cl, o).items():
            wanted[p] = c
        names_seen[o.name] = o.label
    for o in cl.skills:
        if o.name in names_seen:
            cl.errors.append(f"pointer name {o.name} is used by both {names_seen[o.name]} and {o.label}")
            continue
        names_seen[o.name] = o.label
        wanted.update(skill_pointers(cl, o))
    have = existing_pointers(heim.root)
    for p, c in sorted(wanted.items()):
        if p not in have:
            plan.pointers_write[p] = (c, "add")
        elif not same(have[p], c.encode("utf-8")):
            kind = pointer_kind(have[p].decode("utf-8", "replace"))
            if kind == "hand-written":
                plan.pointers_conflict.append(p)
            else:
                plan.pointers_write[p] = (c, "replace" if kind == "heim-sync" else f"replace ({kind})")
    woken_names = {r.split("/")[-1] for r in heim.woken + heim.capabilities}
    for p, b in sorted(have.items()):
        if p in wanted:
            continue
        text = b.decode("utf-8", "replace")
        kind = pointer_kind(text)
        if kind != "hand-written" and pointer_name(p) in woken_names:
            plan.pointers_unresolved.append(p)      # woken, but not in the sources yet: its old pointer stays
        elif kind in ("heim-sync", "legacy") or (kind == "wds" and points_to_agent(text)):
            plan.pointers_remove.append(p)
        elif kind == "wds":
            plan.pointers_kept.append(p)

    # hooks, from the dependencies that are copied (and the Heim's own)
    for o in sorted(cl.objects, key=lambda o: o.label):
        if o.kind != "dependencies":
            continue
        decl, problem = hooks_of(cl.src_dir(o.source) / o.rel)
        if problem:
            plan.hook_problems.append(f"{o.label}: {problem}")
        elif decl:
            plan.hooks[f"{o.source}/{o.rel}"] = decl
    settings_path = heim.root / ".claude" / "settings.json"
    current = {}
    if settings_path.exists():
        try:
            current = json.loads(settings_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            plan.hook_problems.append(f".claude/settings.json is not valid JSON ({e}); heim-sync will not touch it")
            current = None
    if current is not None and (plan.hooks or settings_path.exists()):
        new = merge_hooks(current, plan.hooks)
        if new != current:
            plan.settings_new, plan.settings_change = new, True

    # the session lines in AGENTS.md
    block = session_block(cl, customized_lines(cl, plan.customized))
    agents_md = heim.root / "AGENTS.md"
    if block is None:
        plan.agents_md_note = "no woken agent uses the handover skill; the session lines are not written"
    elif not agents_md.is_file():
        plan.agents_md_note = "no AGENTS.md; the session lines are not written"
    else:
        text = agents_md.read_text(encoding="utf-8")
        new_text = with_session_block(text, block)
        if new_text is None:
            plan.agents_md_note = ("AGENTS.md has no `<!-- heim:session -->` marker; the session lines are not written "
                                   "(put the marker where they belong)")
        elif not same(text.encode("utf-8"), new_text.encode("utf-8")):
            plan.agents_md_new = new_text
    return plan


# ---------- printing ----------

def print_customizations(plan: Plan):
    if not (plan.customized or plan.cust_errors or plan.cust_notes or plan.upstream_changed):
        return
    print(f"\nCustomizations ({plan.heim.rel(plan.cl.cust_dir)}/, never touched by the sync)")
    for o, how in plan.customized:
        print(f"  {o.kind}/{o.name}: {', '.join(how)}")
    for c, msg in plan.upstream_changed:
        print(f"  ! {c} {msg}")
    for e in plan.cust_errors:
        print(f"  x {e}")
    for n in plan.cust_notes:
        print(f"  - {n}")


def print_plan(plan: Plan, verbose: bool, done: bool = False):
    h, cl, info, lim = plan.heim, plan.cl, plan.info, 0 if verbose else LIST_LIMIT
    say = (lambda would, did: did) if done else (lambda would, did: would)
    print(f"Heim:     {h.root.as_posix()} ({h.rel(h.plan)})")
    state = f"{info.repo}@{info.commit or '-'}" + (f" on {info.branch}" if info.branch else "")
    if info.ready():
        state += f"  ! {info.ready()}"
    print(f"Sources:  {cl.sources_dir.as_posix()}  [{', '.join(cl.sources)}]  {state}")
    own_state = "present" if cl.own_dir.is_dir() else "not present"
    n_cust = len(files_under(cl.cust_dir))
    print(f"Agents:   {h.rel(h.agents_dir)}/   own source: {h.rel(cl.own_dir)}/ ({own_state})   "
          f"customizations: {h.rel(cl.cust_dir)}/ ({n_cust} files)")
    print(f"Woken:    agents {', '.join(h.woken) or '-'}; capabilities {', '.join(h.capabilities) or '-'}")

    print("\nWhat is taken")
    by_ref: dict[str, list[Obj]] = {}
    for o, refs in cl.objects.items():
        for r in refs:
            by_ref.setdefault(r, []).append(o)
    for a in cl.agents + [s for s in cl.skills if "heim.yaml capabilities" in cl.objects.get(s, ())]:
        direct = sorted(by_ref.get(a.label, []), key=lambda o: (KINDS.index(o.kind), o.name))
        parts = {}
        for o in direct:
            parts.setdefault(o.kind, []).append(o.name if o.source == a.source else f"{o.source}/{o.name}")
        desc = "; ".join(f"{k} {', '.join(v)}" for k, v in parts.items()) or "nothing more"
        print(f"  {a.label}{' (own)' if a in cl.own_only else ''}: {desc}")
    counts: dict[str, int] = {}
    for o in cl.objects:
        counts[o.kind] = counts.get(o.kind, 0) + 1
    print("  in all: " + ", ".join(f"{counts[k]} {k}" for k in KINDS if k in counts))
    if cl.errors:
        print(f"\nErrors ({len(cl.errors)}): references that do not resolve")
        for e in cl.errors if verbose or len(cl.errors) <= 40 else cl.errors[:40]:
            print(f"  x {e}")
        if not verbose and len(cl.errors) > 40:
            print(f"  … {len(cl.errors) - 40} more; --verbose lists all")
    if cl.notes:
        print("\nNotes")
        for n in dict.fromkeys(cl.notes):
            print(f"  - {n}")

    print(f"\nAgents folder ({say('would change', 'changed')})")
    for fp in plan.folders:
        rel = h.rel(fp.dest) + "/"
        if fp.blocked:
            print(f"  {rel}  NOT TOUCHED: {fp.blocked}")
            continue
        if fp.remove_folder:
            print(f"  {rel}  {say('would be removed', 'removed')} (nothing woken uses it; {len(fp.delete)} files)")
            continue
        old = (fp.old or {}).get("source", "none")
        new = re.search(r"^source:\s*(.+)$", fp.source_text, re.M).group(1)
        print(f"  {rel}  .source: {old} -> {new}")
        if not (fp.new or fp.update or fp.delete):
            print("    files: no change" + ("; .source updated" if fp.write_source else ""))
        for label, items in (("add", fp.new), ("update", fp.update), ("remove", fp.delete), ("EDITED IN THE COPY", fp.edited)):
            if items:
                print(f"    {label} ({len(items)}): {show(items, lim)}")
        if fp.old is not None and "files" not in fp.old and not fp.blocked:
            print("    (the old .source records no file hashes, so edits in the copy cannot be seen this time)")
    for x in plan.left_alone:
        print(f"  {x}  left alone")

    print_customizations(plan)

    print(f"\nPointers ({say('would change', 'changed')})")
    adds = [p for p, (_, k) in plan.pointers_write.items() if k == "add"]
    reps = [f"{p}" + (f" [{k[9:-1]}]" if k.startswith("replace (") else "") for p, (_, k) in plan.pointers_write.items() if k != "add"]
    for label, items in (("add", adds), ("replace", reps), ("remove", plan.pointers_remove)):
        if items:
            print(f"  {label} ({len(items)}): {show(items, lim)}")
    if not (adds or reps or plan.pointers_remove):
        print("  no change")
    if plan.pointers_conflict:
        print(f"  hand-written, not touched ({len(plan.pointers_conflict)}): {show(plan.pointers_conflict, lim)}")
    if plan.pointers_unresolved:
        print(f"  kept, woken but not in the sources yet ({len(plan.pointers_unresolved)}): {show(plan.pointers_unresolved, lim)}")
    if plan.pointers_kept:
        print(f"  WDS pointers that are not agents, left for the switch ({len(plan.pointers_kept)}): {show(plan.pointers_kept, lim)}")

    if plan.hooks or plan.settings_change or plan.hook_problems:
        print(f"\nHooks in .claude/settings.json ({say('would change', 'changed') if plan.settings_change else 'no change'})")
        for label, decl in plan.hooks.items():
            for event, groups in decl.items():
                for g in groups:
                    for hk in g.get("hooks", []):
                        cmd = " ".join(str(hk.get("command", "")).split())
                        print(f"  {event} from {label}: {cmd if verbose else cmd[:160] + ('…' if len(cmd) > 160 else '')}")
        for p in plan.hook_problems:
            print(f"  x {p}")

    print(f"\nSession lines in AGENTS.md ({say('would change', 'changed') if plan.agents_md_new else 'no change'})")
    if plan.agents_md_note:
        print(f"  - {plan.agents_md_note}")


